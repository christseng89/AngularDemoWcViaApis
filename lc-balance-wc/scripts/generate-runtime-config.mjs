import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const envPath = resolve(root, '.env');
const outputPath = resolve(root, 'src/app/core/http-retry/http-retry.config.generated.ts');
const taxonomyPath = resolve(root, 'microservices/balance-component/config/balance-account-mappings.json');
const taxonomyOutputPath = resolve(root, 'src/app/core/balance-account-taxonomy.generated.ts');

function readEnvFile(path) {
  try {
    return Object.fromEntries(
      readFileSync(path, 'utf8')
        .split(/\r?\n/)
        .map((line) => line.trim())
        .filter((line) => line && !line.startsWith('#') && line.includes('='))
        .map((line) => {
          const separator = line.indexOf('=');
          return [line.slice(0, separator).trim(), line.slice(separator + 1).trim().replace(/^['"]|['"]$/g, '')];
        }),
    );
  } catch (error) {
    if (error?.code === 'ENOENT') return {};
    throw error;
  }
}

const fileEnv = readEnvFile(envPath);
const rawCount = process.env.BALANCE_HTTP_RETRY_COUNT ?? fileEnv.BALANCE_HTTP_RETRY_COUNT ?? '3';
const rawInitialDelay = process.env.BALANCE_HTTP_RETRY_INITIAL_DELAY_MS ?? fileEnv.BALANCE_HTTP_RETRY_INITIAL_DELAY_MS ?? '250';
const rawMaxDelay = process.env.BALANCE_HTTP_RETRY_MAX_DELAY_MS ?? fileEnv.BALANCE_HTTP_RETRY_MAX_DELAY_MS ?? '2000';
const rawBusinessCaseRecoveryCount = process.env.BUSINESS_CASE_RECOVERY_RETRY_COUNT ?? fileEnv.BUSINESS_CASE_RECOVERY_RETRY_COUNT ?? '15';
const rawBusinessCaseRecoveryInterval = process.env.BUSINESS_CASE_RECOVERY_INTERVAL_MS ?? fileEnv.BUSINESS_CASE_RECOVERY_INTERVAL_MS ?? '2000';
const retryCount = Number.parseInt(rawCount, 10);
const initialDelayMs = Number.parseInt(rawInitialDelay, 10);
const maxDelayMs = Number.parseInt(rawMaxDelay, 10);
const businessCaseRecoveryRetryCount = Number.parseInt(rawBusinessCaseRecoveryCount, 10);
const businessCaseRecoveryIntervalMs = Number.parseInt(rawBusinessCaseRecoveryInterval, 10);

if (!Number.isInteger(retryCount) || retryCount < 0 || retryCount > 10) {
  throw new Error('BALANCE_HTTP_RETRY_COUNT must be an integer between 0 and 10.');
}
if (!Number.isInteger(initialDelayMs) || initialDelayMs < 0 || initialDelayMs > 60_000) {
  throw new Error('BALANCE_HTTP_RETRY_INITIAL_DELAY_MS must be an integer between 0 and 60000.');
}
if (!Number.isInteger(maxDelayMs) || maxDelayMs < initialDelayMs || maxDelayMs > 60_000) {
  throw new Error('BALANCE_HTTP_RETRY_MAX_DELAY_MS must be an integer between the initial delay and 60000.');
}
if (!Number.isInteger(businessCaseRecoveryRetryCount) || businessCaseRecoveryRetryCount < 0 || businessCaseRecoveryRetryCount > 60) {
  throw new Error('BUSINESS_CASE_RECOVERY_RETRY_COUNT must be an integer between 0 and 60.');
}
if (!Number.isInteger(businessCaseRecoveryIntervalMs) || businessCaseRecoveryIntervalMs < 100 || businessCaseRecoveryIntervalMs > 60_000) {
  throw new Error('BUSINESS_CASE_RECOVERY_INTERVAL_MS must be an integer between 100 and 60000.');
}

writeFileSync(
  outputPath,
  `// Generated by scripts/generate-runtime-config.mjs. Do not edit manually.\n` +
    `export const GENERATED_HTTP_RETRY_COUNT = ${retryCount};\n` +
    `export const GENERATED_HTTP_RETRY_INITIAL_DELAY_MS = ${initialDelayMs};\n` +
    `export const GENERATED_HTTP_RETRY_MAX_DELAY_MS = ${maxDelayMs};\n` +
    `export const GENERATED_BUSINESS_CASE_RECOVERY_RETRY_COUNT = ${businessCaseRecoveryRetryCount};\n` +
    `export const GENERATED_BUSINESS_CASE_RECOVERY_INTERVAL_MS = ${businessCaseRecoveryIntervalMs};\n`,
);

const taxonomy = JSON.parse(readFileSync(taxonomyPath, 'utf8'));
if (!Array.isArray(taxonomy.categories) || !Array.isArray(taxonomy.families)) {
  throw new Error('Balance Account taxonomy must define categories and families.');
}
const tenorOptions = Object.fromEntries(
  taxonomy.categories.map((category) => [
    category.categoryKey,
    category.tenorTypes.map(({ apiValue, label, behavior, tenorKey }) => ({ value: apiValue, label, behavior, tenorKey })),
  ]),
);
writeFileSync(
  taxonomyOutputPath,
  `// Generated from microservices/balance-component/config/balance-account-mappings.json. Do not edit manually.\n` +
    `export const GENERATED_TENOR_OPTIONS = ${JSON.stringify(tenorOptions, null, 2)} as const;\n`,
);

console.log(
  `Generated HTTP retry configuration: ${retryCount} retries, ${initialDelayMs}-${maxDelayMs}ms backoff; ` +
    `Business Case recovery: ${businessCaseRecoveryRetryCount} retries every ${businessCaseRecoveryIntervalMs}ms.`,
);
console.log(`Generated Balance Account taxonomy: ${taxonomy.categories.length} categories, ${taxonomy.families.length} business/GL families.`);
